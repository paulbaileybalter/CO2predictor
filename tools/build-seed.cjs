/* Re-generates public/data.js from the two spreadsheets.
   Usage:  npm i --no-save xlsx@0.18.5   then   node tools/build-seed.cjs <Live_Brewery_Board.xlsx> <Co2_tracking.xlsx> [year]   */
const fs = require('fs'); const path = require('path');
const XLSX = require('xlsx'); const LBB = require('../public/lbb.js');
const [boardFile, co2File, yearArg] = process.argv.slice(2);
if (!boardFile || !co2File) { console.error('usage: node tools/build-seed.cjs <board.xlsx> <co2.xlsx> [year]'); process.exit(1); }
const year = +yearArg || new Date().getFullYear();
const board = LBB.parseBoardWorkbook(XLSX.read(fs.readFileSync(boardFile)), XLSX, { minDate: `${year}-07-27` });
const readings = LBB.parseCo2Workbook(XLSX.read(fs.readFileSync(co2File)), XLSX, year);
const seed = { version: new Date().toISOString(), board: board.days, readings };
fs.writeFileSync(path.join(__dirname, '../public/data.js'), '/* generated by tools/build-seed.cjs */\nwindow.SEED = ' + JSON.stringify(seed) + ';\n');
console.log('board days:', Object.keys(board.days).length, '| sheets:', board.sheets.length, '| readings:', readings.length);
if (board.mismatches.length) console.log('Weekly total mismatches (board B51/B52 vs parsed):', JSON.stringify(board.mismatches));
